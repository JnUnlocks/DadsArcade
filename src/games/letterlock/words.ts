/**
 * Letter Lock's two word lists.
 *
 * ANSWERS is the short one: every word the game will ever ask for. It was
 * written by hand for this arcade, and the bar is "a seven-year-old could
 * meet this word in a reading book". No swears, nothing rude, nothing about
 * fighting, drinking or smoking, no body parts, and nothing so obscure that
 * losing to it feels like a trick. The common words that British and American
 * English spell differently are left out too, so nobody loses a try to a
 * spelling argument. words.test.ts holds a blocklist against it.
 *
 * The daily word walks a fixed shuffle of ANSWERS (rules.ts), so changing this
 * list -- even adding to the end -- reshuffles every future day. That's fine
 * between releases, but two phones on different builds would then disagree
 * about today's word until both have updated.
 *
 * MORE_GUESSES is the long one: every other five-letter word a guess may be.
 * It is the public-domain ENABLE word list filtered to five letters, minus a
 * few dozen swears and slurs, so that typing one gets NOT IN THE LIST rather
 * than a row of tiles. It's packed: each chunk is a two-letter start followed
 * by every three-letter ending that goes with it, run together ("aahedliirgh"
 * is aahed, aalii, aargh). Sorted words share their first two letters so often
 * that this keeps 7,377 words to about 11 KB of the download, against 17 KB
 * written out in full.
 */

