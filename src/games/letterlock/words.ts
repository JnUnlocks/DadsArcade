function unpack(packed: string): string[] {
  const words: string[] = [];
  for (const chunk of packed.trim().split(/\s+/)) {
    const start = chunk.slice(0, 2);
    for (let i = 2; i < chunk.length; i += 3) words.push(start + chunk.slice(i, i + 3));
  }
  return words;
}

/** Every word a guess may be: the answers, plus the long list. */
export const ALLOWED: ReadonlySet<string> = new Set([...ANSWERS, ...unpack(MORE_GUESSES)]);

/** True for a real five-letter word, in lower case. */
export function isAllowedGuess(word: string): boolean {
  return ALLOWED.has(word);
}
